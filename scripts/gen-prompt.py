#!/usr/bin/env python3
"""gen-prompt.py — 由 prompt/ 生成四个运行时的系统提示词字面量与 tools.json。

单一来源：prompt/*.txt 与 prompt/tools.json。
生成产物（均提交进仓库，勿手改）：
  src/agent.sh            仅改写 BEGIN/END GENERATED 标记之间的内容
  go/prompt_gen.go
  rust/src/prompt_gen.rs
  c/prompt_gen.h

带 {{NAME}} 占位符的模板按占位符切成若干段（NAME_0、NAME_1 ...），
由各运行时直接拼接，不在运行时做字符串替换。

用法:
  scripts/gen-prompt.py          生成并写盘
  scripts/gen-prompt.py --check  只比对，不一致时列出文件并以非零退出
仅依赖 Python 标准库。
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROMPT_DIR = os.path.join(ROOT, "prompt")

# (源文件, 常量名, 按出现顺序排列的占位符)
SPEC = [
    ("identity.en.txt", "IDENTITY_EN", []),
    ("identity.zh.txt", "IDENTITY_ZH", []),
    ("rules.txt", "RULES", []),
    ("tool_guidance.txt", "TOOL_GUIDANCE", []),
    ("sub_agent_guidance.txt", "SUB_AGENT_GUIDANCE", []),
    ("todo_guidance.txt", "TODO_GUIDANCE", []),
    ("plan_lifecycle.txt", "PLAN_LIFECYCLE", ["PLAN_DRAFT_FILE", "PLAN_FILE"]),
    ("output_language.en.txt", "OUTPUT_LANGUAGE_EN", ["LOCALE"]),
    ("output_language.zh.txt", "OUTPUT_LANGUAGE_ZH", []),
]

PLACEHOLDER_RE = re.compile(r"\{\{([A-Z_]+)\}\}")

BASH_BEGIN = "# >>> BEGIN GENERATED by scripts/gen-prompt.py"
BASH_END = "# <<< END GENERATED"
NOTICE = "由 scripts/gen-prompt.py 生成，勿手改；修改 prompt/ 后运行 make gen-prompt"


def die(msg):
    print("gen-prompt: " + msg, file=sys.stderr)
    sys.exit(1)


def read_text(name):
    path = os.path.join(PROMPT_DIR, name)
    with open(path, encoding="utf-8", newline="") as f:
        text = f.read()
    # 约定：文件末尾的一个换行不属于字面量
    if text.endswith("\n"):
        text = text[:-1]
    if "\r" in text:
        die(name + ": 不允许 CR 字符")
    return text


def load_constants():
    """返回 [(常量名, 字符串)]，模板已按占位符切段。"""
    consts = []
    for fname, cname, expected in SPEC:
        text = read_text(fname)
        found = PLACEHOLDER_RE.findall(text)
        if found != expected:
            die("%s: 占位符应为 %r，实际为 %r" % (fname, expected, found))
        if not expected:
            consts.append((cname, text))
            continue
        parts = PLACEHOLDER_RE.split(text)[0::2]
        for i, part in enumerate(parts):
            consts.append(("%s_%d" % (cname, i), part))
    return consts


def load_tools_json():
    with open(os.path.join(PROMPT_DIR, "tools.json"), encoding="utf-8", newline="") as f:
        return f.read()


def split_lines(text):
    """按行切分并保留每行末尾的 \\n，便于生成可读的多段字面量。"""
    if text == "":
        return [""]
    return text.splitlines(keepends=True)


# ---------- Bash ----------

def bash_quote(s):
    out = ["$'"]
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    out.append("'")
    return "".join(out)


def gen_bash_block(consts, tools_json):
    lines = [BASH_BEGIN + " — " + NOTICE]
    for name, value in consts:
        lines.append("PROMPT_%s=%s" % (name, bash_quote(value)))
    # 与原 TOOL_DEF_JSON=$(<file) 语义一致：去掉末尾换行
    lines.append("PROMPT_TOOLS_JSON=%s" % bash_quote(tools_json.rstrip("\n")))
    lines.append(BASH_END)
    return "\n".join(lines) + "\n"


def render_bash(consts, tools_json):
    path = os.path.join(ROOT, "src", "agent.sh")
    with open(path, encoding="utf-8", newline="") as f:
        content = f.read()
    lines = content.split("\n")
    begins = [i for i, l in enumerate(lines) if l.startswith(BASH_BEGIN)]
    ends = [i for i, l in enumerate(lines) if l == BASH_END]
    if len(begins) != 1 or len(ends) != 1:
        die("src/agent.sh: BEGIN/END GENERATED 标记必须各出现一次（BEGIN=%d, END=%d）"
            % (len(begins), len(ends)))
    b, e = begins[0], ends[0]
    if e < b:
        die("src/agent.sh: END GENERATED 出现在 BEGIN 之前")
    block = gen_bash_block(consts, tools_json).rstrip("\n").split("\n")
    new_lines = lines[:b] + block + lines[e + 1:]
    return path, "\n".join(new_lines)


# ---------- Go ----------

def go_camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))


def go_quote(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def go_multiline(s):
    # const 块内续行比声明多缩进一级（与 gofmt 一致）
    return " +\n\t\t".join(go_quote(p) for p in split_lines(s))


def render_go(consts, tools_json):
    out = ["// Code generated by scripts/gen-prompt.py. DO NOT EDIT.",
           "// " + NOTICE, "", "package agent", "", "const ("]
    for name, value in consts:
        out.append("\tprompt%s = %s" % (go_camel(name), go_multiline(value)))
        out.append("")
    out.append("\tpromptToolsJSON = " + go_multiline(tools_json))
    out.append(")")
    return os.path.join(ROOT, "go", "prompt_gen.go"), "\n".join(out) + "\n"


# ---------- Rust ----------

def rust_quote(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def rust_multiline(s):
    parts = split_lines(s)
    if len(parts) == 1:
        return rust_quote(parts[0])
    body = ",\n    ".join(rust_quote(p) for p in parts)
    return "concat!(\n    " + body + ",\n)"


def render_rust(consts, tools_json):
    out = ["// @generated by scripts/gen-prompt.py. DO NOT EDIT.",
           "// " + NOTICE, ""]
    for name, value in consts:
        out.append("pub const PROMPT_%s: &str = %s;" % (name, rust_multiline(value)))
        out.append("")
    out.append("pub const TOOLS_JSON: &str = %s;" % rust_multiline(tools_json))
    return os.path.join(ROOT, "rust", "src", "prompt_gen.rs"), "\n".join(out) + "\n"


# ---------- C ----------

def c_quote(s):
    out = ['"']
    n = len(s)
    for i, ch in enumerate(s):
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "?" and i + 1 < n and s[i + 1] == "?":
            out.append("\\?")  # 防三字符组（-std=c11 下 gcc 会解析 ??x）
        elif o < 0x20 or o == 0x7F:
            out.append("\\%03o" % o)  # 定长八进制，避免 \x 吞掉后续十六进制字符
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def c_multiline(s):
    return "\n    ".join(c_quote(p) for p in split_lines(s))


def render_c(consts, tools_json):
    out = ["/* " + NOTICE + " */",
           "#ifndef PROMPT_GEN_H", "#define PROMPT_GEN_H", ""]
    for name, value in consts:
        out.append("static const char PROMPT_%s[] =\n    %s;" % (name, c_multiline(value)))
        out.append("")
    out.append("static const char PROMPT_TOOLS_JSON[] =\n    %s;" % c_multiline(tools_json))
    out.append("")
    out.append("#endif /* PROMPT_GEN_H */")
    return os.path.join(ROOT, "c", "prompt_gen.h"), "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv[1:]
    unknown = [a for a in argv[1:] if a != "--check"]
    if unknown:
        die("未知参数: " + " ".join(unknown))

    consts = load_constants()
    tools_json = load_tools_json()
    outputs = [
        render_bash(consts, tools_json),
        render_go(consts, tools_json),
        render_rust(consts, tools_json),
        render_c(consts, tools_json),
    ]

    stale = []
    for path, content in outputs:
        try:
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == content:
            continue
        rel = os.path.relpath(path, ROOT)
        if check:
            stale.append(rel)
        else:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(content)
            print("gen-prompt: 已更新 " + rel)

    if check:
        if stale:
            print("gen-prompt: 以下生成文件与 prompt/ 不一致，请运行 make gen-prompt：", file=sys.stderr)
            for rel in stale:
                print("  " + rel, file=sys.stderr)
            return 1
        print("gen-prompt: 生成文件均为最新")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
